let valor = 10;
console.log(`Valor = ${valor}`)

// Soma
// valor = valor + 5
valor+=5
console.log(`Valor = ${valor}`)

// subtração
valor-=5;
console.log(`Valor = ${valor}`)

// multiplicação
valor*=5;
console.log(`Valor = ${valor}`)

// divisão
valor/=5;
console.log(`Valor = ${valor}`)

// módulo
valor%=5;
console.log(`Valor = ${valor}`)