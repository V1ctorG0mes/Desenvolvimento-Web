const numero = 97.95;
console.log(numero);

// arredonda para o próximo inteiro
console.log(Math.ceil(numero));

// arredondamento para o próprio inteiro
console.log(Math.floor(numero));

// caso decimal seja menor que 50 = DEIXAR NO PRÓPRIO INTEIRO
// caso decimal seja maior ou igual a 50 = PRÓXIMO INTEIRO
console.log(Math.round(numero));
console.log(Math.round(97.15));

// maior número em uma lista
console.log(Math.max(12, 18, 89, 56, 112, 8, 155, 203));

// menor número em uma lista
console.log(Math.min(12, 18, 89, 56, 112, 8, 155, 203));

// portência
console.log(2**8);
console.log(Math.pow(2,8));

// sorteia um número entre 0 e 1
console.log(Math.random());

// raiz quadrada
console.log(Math.sqrt(256));

// raiz cúbica
console.log(Math.cbrt(27));
